export function getMessage(locale: Locale, key: TranslationKey): string {
  const messages = locale === "en-US" ? enUSMessages : zhCNMessages
  return messages[key] ?? key
}

export function translateText(text: string, locale: Locale): string {
  if (locale === "zh-CN" || !/[\u4e00-\u9fff]/.test(text)) return text

  const exact = enPhraseMap[text]
  if (exact) return exact

  for (const [pattern, replacement] of tokenPhraseMap) {
    if (pattern.test(text)) return text.replace(pattern, replacement)
  }

  let translated = text
  const entries = Object.entries(enPhraseMap).sort(
    (a, b) => b[0].length - a[0].length
  )
  for (const [source, target] of entries) {
    if (source && translated.includes(source)) {
      translated = translated.split(source).join(target)
    }
  }

  return translated
}

export function translateApiErrorMessage(
  code: string | undefined,
  message: string | undefined,
  locale: Locale
): string | undefined {
  if (locale === "zh-CN") return message
  if (message) {
    const translated = translateText(message, locale)
    if (translated !== message) return translated
  }
  const key = code ? (`api.${code}` as TranslationKey) : null
  if (key && key in enUSMessages) return enUSMessages[key]
  return message
}

export function interpolate(
  template: string,
  params?: Record<string, unknown>
) {
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (_, key: string) => {
    const value = params[key]
    return value === undefined || value === null ? "" : String(value)
  })
}
